import { chromium } from 'playwright';
const W = +(process.argv[2] || 1440);
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: W, height: 900 } })).newPage();
await p.goto('http://localhost:8797/job-search-proposed.html', { waitUntil: 'networkidle' });
await p.waitForTimeout(600);
const out = await p.evaluate(() => {
  const r = (sel, i=0) => { const e = document.querySelectorAll(sel)[i]; if (!e) return 'MISSING '+sel; const x = e.getBoundingClientRect(); return [Math.round(x.left), Math.round(x.top+scrollY), Math.round(x.width), Math.round(x.height)]; };
  const lines = [];
  lines.push('hero h1 ' + r('.job-hero h1'));
  lines.push('cvm-section ' + r('.cvm-band'));
  lines.push('cvm-caption ' + r('.cvm-caption'));
  lines.push('jic h2 ' + r('.jic-count h2'));
  lines.push('results-band ' + r('.results-band'));
  lines.push('src-header ' + r('.src-header'));
  lines.push('select-box ' + r('.select-box'));
  lines.push('fav-link ' + r('.fav-link'));
  lines.push('ol ' + r('.job-results ol'));
  document.querySelectorAll('.job-results ol li').forEach((li,i)=>{ const x=li.getBoundingClientRect(); lines.push('li'+i+' ['+Math.round(x.left)+','+Math.round(x.top+scrollY)+','+Math.round(x.width)+','+Math.round(x.height)+']'); });
  lines.push('loadmore ' + r('.load-more button'));
  lines.push('job-side ' + r('.job-side'));
  lines.push('job-alert-btn ' + r('.alert-btn'));
  lines.push('jfc ' + r('.job-filter'));
  lines.push('fgroup0 ' + r('.filter-form .form-group',0));
  lines.push('toggle ' + r('.toggle-more'));
  lines.push('kwzone ' + r('.kw-zone'));
  lines.push('htm ' + r('.htm-band'));
  lines.push('note ' + r('.note-band'));
  lines.push('explore ' + r('.explore-band'));
  lines.push('explore h2 ' + r('.explore-head h2'));
  lines.push('exp-row ' + r('.explore-row'));
  lines.push('card-body0 ' + r('.card-body',0));
  lines.push('breadcrumb ' + r('#breadcrumb-bottom'));
  lines.push('body ' + document.body.scrollHeight);
  return lines.join('\n');
});
console.log(out);
await b.close();
